/**
 * The board. It answers three questions in this order: what needs me, what is moving, what is next.
 * A healthy, empty section takes no space.
 */
import type { LaneRecord, State, TaskContract } from './model.ts'
import type { Packet } from './plan.ts'

export interface BoardInput {
  readonly repo: string
  readonly now: string
  readonly contracts: readonly TaskContract[]
  readonly state: State
  readonly packet: Packet
  readonly problems: readonly string[]
}

function age(from: string, now: string): string {
  const ms = Date.parse(now) - Date.parse(from)
  if (!Number.isFinite(ms) || ms < 0) return '—'
  const minutes = Math.round(ms / 60_000)
  if (minutes < 60) return `${minutes}m`
  const hours = Math.round(minutes / 60)
  return hours < 48 ? `${hours}h` : `${Math.round(hours / 24)}d`
}

function cell(text: string): string {
  return text.replaceAll('|', '\\|').replace(/\s+/g, ' ').trim()
}

export function board(input: BoardInput): string {
  const { packet, state, now } = input
  const title = new Map(input.contracts.map((task) => [task.id, task.title]))
  const name = (id: string) => `${id} ${title.get(id) ?? ''}`.trim()
  const lane = (id: string): LaneRecord | undefined => state.lanes[id]
  const lines: string[] = [
    `# ${input.repo} — work board`,
    '',
    `Generated by rw at ${now}. Do not edit: run \`rw status\`.`,
    '',
  ]
  const next = packet.halt
    ? `HALT — ${packet.haltReason}`
    : [
        packet.ready.length ? `dispatch ${packet.ready.join(', ')}` : '',
        packet.review.length ? `review/merge ${packet.review.join(', ')}` : '',
        packet.running.length ? `${packet.running.length} running` : '',
      ].filter(Boolean).join('; ')
  lines.push(`Next: ${next}`, '')

  if (input.problems.length) {
    lines.push('## Problems', '', ...input.problems.map((problem) => `- ${problem}`), '')
  }
  if (packet.attention.length) {
    lines.push('## Needs you', '', '| Task | State | Ask |', '| --- | --- | --- |')
    for (const item of packet.attention) lines.push(`| ${cell(name(item.task))} | ${item.state} | ${cell(item.ask)} |`)
    lines.push('')
  }
  if (packet.running.length || packet.review.length) {
    lines.push('## Moving', '', '| Task | State | Executor | Age | Note |', '| --- | --- | --- | --- | --- |')
    for (const id of [...packet.running, ...packet.review]) {
      const record = state.tasks[id]
      const run = lane(id)
      const review = record?.state === 'review' ? (record.reviewVerdict === 'approve' ? 'review approved' : 'awaiting review/merge') : ''
      const note = [review, record?.remediation ? `remediation ${record.remediation}` : '', record?.note ?? ''].filter(Boolean).join('; ')
      lines.push(`| ${cell(name(id))} | ${record?.state ?? ''} | ${run ? `${run.executor}${run.model ? `/${run.model}` : ''}` : '—'} | ${record ? age(record.since, now) : '—'} | ${cell(note)} |`)
    }
    lines.push('')
  }
  if (packet.ready.length || packet.waiting.length) {
    lines.push('## Queue', '', '| Task | Status |', '| --- | --- |')
    for (const id of packet.ready) lines.push(`| ${cell(name(id))} | ready |`)
    for (const item of packet.waiting) lines.push(`| ${cell(name(item.task))} | ${cell(item.reason)} |`)
    lines.push('')
  }
  lines.push(`Done ${packet.done} · dropped ${packet.dropped}.`)
  return `${lines.join('\n')}\n`
}
